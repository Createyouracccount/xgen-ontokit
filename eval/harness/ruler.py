"""사전 등록 자(ruler) 강제 적용 — **산문 판단에 맡기지 않는다**.

## 왜 필요한가

R5 와 R7 에서 **같은 사고가 두 번** 났다:

- R5: 독립 심판 3인이 **만장일치로** 아파트 단지명을 `지역` 클래스에서 **참**으로 판정했다.
  그러나 사전 등록 기준(`roster_precision_predeclare.md` §3)은 *"시설 = 거짓"* 이었다.
  K-1 대로 **먼저 고정된 자**를 채택해 오살 1/70 로 처리했다.
- R7: 같은 유형이 **이득 51건에 6건** 들어왔다 — `서울추모공원`(R5 에서 이미 처분된
  **바로 그 라벨**) · `제2여객터미널`(사전 공시가 **거짓 예시로 명시**한 라벨) ·
  `e편한세상부평역센트럴파크` · `원당역롯데캐슬스카이엘` · `시안가족추모공원` · `제1전시관`.
  적용하면 **45/99 = 45.45%** 로 임계 미달인데, 산문으로 처리하다 누락했다.

**심판이 정합하되 옳지 않을 수 있다.** 심판 일치는 사전 등록 자를 이기지 못한다(K-1).
그러므로 자 적용을 **채점기가 강제**한다.

## 규칙 (사전 등록 · `roster_precision_predeclare.md` §3)

시설·건물·단지·터미널·전시관 등은 **인물/기관/지역 어느 것도 아니다** → 거짓.
이 판정은 심판 다수결을 **덮어쓴다**.
"""
from __future__ import annotations

import re

# 사전 등록 자 — 시설/건물/단지 표지. 라벨 **끝**에 오면 시설로 본다.
# ⚠️ **좁게 유지한다.** 과대 규칙은 R4·R5 를 죽인 유형이다(스톱리스트가 정당 라벨을 잘랐다).
#    실측 오탐: `센터` 를 넣었더니 `한국유통정보센터`(기관)가 시설로 잡혔다 — 뺐다.
#    `연구센터`·`정보센터`·`지원센터` 는 조직명이 대부분이라 접미로 판별 불가하다.
#    이 목록이 못 잡는 시설은 **미커버**로 남기고 그 사실을 공시한다(판례 19).
FACILITY_SUFFIX = (
    "아파트", "단지", "터미널", "전시관", "추모공원", "공원묘지",
    "빌딩", "타워", "스카이엘", "캐슬", "자이", "푸르지오",
    "위브", "더샵", "래미안", "센트럴파크", "한신더휴", "우미린", "e편한세상",
)
# 분양 브랜드가 라벨 **내부**에 오는 경우 (지명+브랜드 결합)
FACILITY_INFIX = ("위브더", "롯데캐슬", "힐스테이트", "e편한세상", "아이파크", "더샵")

_HALL = re.compile(r"제\d+(여객터미널|전시관|전시장|공항|청사)$")


def is_facility(label: str) -> bool:
    """사전 등록 자: 시설·건물·단지인가. 참이면 3분류 어디에도 속하지 않는다."""
    s = (label or "").strip()
    if not s:
        return False
    if _HALL.search(s):
        return True
    if s.endswith(FACILITY_SUFFIX):
        return True
    return any(k in s for k in FACILITY_INFIX)


def apply(verdicts: dict, labels: dict) -> dict:
    """다수결 판정에 사전 등록 자를 **덮어쓴다**. 덮어쓴 내역을 함께 낸다.

    verdicts: {id: '참'|'거짓'|'판정불가'}   labels: {id: label}
    """
    out, overridden = {}, []
    for i, v in verdicts.items():
        lb = labels.get(i, "")
        if is_facility(lb) and v == "참":
            out[i] = "거짓"
            overridden.append({"id": i, "label": lb, "심판다수결": v,
                               "사전등록자": "거짓(시설)"})
        else:
            out[i] = v
    return {"판정": out, "자_덮어씀": overridden, "덮어쓴수": len(overridden)}
